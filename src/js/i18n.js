export const LANGS = Object.keys(DICT);
let lang = 'fr';

export function setLang(value) {
  lang = LANGS.includes(value) ? value : 'fr';
  document.documentElement.lang = lang;
}

export function getLang() {
  return lang;
}

/** Traduit une clé ; {x} est remplacé par vars.x. Une clé inconnue est renvoyée telle quelle. */
export function t(key, vars = {}) {
  const text = DICT[lang][key] ?? DICT.fr[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '');
}

/** Langue de départ : URL, puis préférence enregistrée, puis navigateur. */
export function detectLang(fromUrl, stored) {
  if (LANGS.includes(fromUrl)) return fromUrl;
  if (LANGS.includes(stored)) return stored;
  const nav = (globalThis.navigator?.language ?? 'fr').slice(0, 2);
  return LANGS.includes(nav) ? nav : 'fr';
}

/** Applique les traductions aux éléments statiques marqués data-i18n / data-i18n-placeholder. */
export function translateDom(root = document) {
  for (const node of root.querySelectorAll('[data-i18n]')) node.textContent = t(node.dataset.i18n);
  for (const node of root.querySelectorAll('[data-i18n-placeholder]')) node.placeholder = t(node.dataset.i18nPlaceholder);
}

/** Pour les tests : toutes les clés existent dans toutes les langues. */
export function missingKeys() {
  const out = [];
  for (const l of LANGS) for (const k of Object.keys(DICT.fr)) if (!(k in DICT[l])) out.push(`${l}:${k}`);
  for (const l of LANGS) for (const k of Object.keys(DICT[l])) if (!(k in DICT.fr)) out.push(`fr:${k}`);
  return out;
}
